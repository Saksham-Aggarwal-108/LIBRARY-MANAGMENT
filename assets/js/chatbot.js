/**
 * BookNest AI Assistant - "Kaira" Main Controller
 * Built strictly with Vanilla JavaScript and Native Promises
 * Compulsory usage: Promise, async/await, .then(), .catch(), .finally()
 */

(function () {
  'use strict';

  // State
  let conversationId = sessionStorage.getItem('bn_chatbot_conv_id') || null;
  let isSending = false;
  let isOpen = false;
  let lastFailedMessage = null;

  // DOM Elements cache
  let dom = {
    root: null,
    fab: null,
    window: null,
    messages: null,
    form: null,
    input: null,
    sendBtn: null,
    clearBtn: null,
    closeBtn: null,
    badge: null
  };

  /**
   * Helper: Native Promise to delay/timeout if needed
   */
  function delay(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
  }

  /**
   * Format basic markdown-like syntax into safe HTML
   */
  function formatMessageText(text) {
    if (!text) return '';
    
    // Escape HTML first to prevent XSS
    let escaped = text
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');

    // Allow safe anchor tags for login links generated by our backend
    escaped = escaped.replace(/&lt;a href="([^"]+)" class="([^"]+)"&gt;([^&]+)&lt;\/a&gt;/g, '<a href="$1" class="$2">$3</a>');

    // Bold: **text**
    escaped = escaped.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');

    // Italic: *text*
    escaped = escaped.replace(/\*(.*?)\*/g, '<em>$1</em>');

    // Bullet points: lines starting with • or * or -
    const lines = escaped.split('\n');
    let inList = false;
    let formattedLines = [];

    lines.forEach(line => {
      const trimmed = line.trim();
      if (trimmed.startsWith('• ') || trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
        if (!inList) {
          inList = true;
          formattedLines.push('<ul>');
        }
        formattedLines.push(`<li>${trimmed.substring(2)}</li>`);
      } else {
        if (inList) {
          inList = false;
          formattedLines.push('</ul>');
        }
        if (trimmed.length > 0) {
          formattedLines.push(`<p>${line}</p>`);
        }
      }
    });

    if (inList) {
      formattedLines.push('</ul>');
    }

    return formattedLines.join('');
  }

  /**
   * Format current time (e.g. "10:30 AM")
   */
  function getCurrentTime() {
    const now = new Date();
    return now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  }

  /**
   * Inject Chatbot DOM Elements if not already present
   */
  function injectChatbotDOM() {
    if (document.getElementById('chatbot-root')) {
      return Promise.resolve();
    }

    return new Promise((resolve) => {
      const root = document.createElement('div');
      root.id = 'chatbot-root';
      root.innerHTML = `
        <!-- Floating Launcher (FAB) -->
        <div class="chatbot-fab-wrap">
          <span id="chatbot-fab-tooltip" class="chatbot-fab-tooltip">Chat with Kaira</span>
          <button id="chatbot-fab" class="chatbot-fab" aria-label="Open BookNest AI Assistant">
            <span class="chatbot-fab-badge" id="chatbot-badge"></span>
            <img src="assets/images/kaira-avatar.jpg" alt="Kaira Chatbot" class="chatbot-fab-avatar">
            <svg class="chatbot-fab-icon icon-close" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round">
              <line x1="18" y1="6" x2="6" y2="18"></line>
              <line x1="6" y1="6" x2="18" y2="18"></line>
            </svg>
          </button>
        </div>

        <!-- Chatbot Window -->
        <div id="chatbot-window" class="chatbot-window" role="dialog" aria-labelledby="chatbot-title" aria-modal="true">
          <!-- Header -->
          <div class="chatbot-header">
            <div class="chatbot-header-info">
              <div class="chatbot-avatar">
                <img src="assets/images/kaira-avatar.jpg" alt="Kaira Avatar" class="chatbot-avatar-img">
                <span class="chatbot-status-indicator" title="Kaira is online"></span>
              </div>
              <div class="chatbot-titles">
                <span id="chatbot-title" class="chatbot-title">Kaira</span>
                <span class="chatbot-subtitle">Your Smart Library Companion</span>
              </div>
            </div>
            <div class="chatbot-header-actions">
              <button id="chatbot-clear-btn" class="chatbot-btn-icon" aria-label="Clear chat conversation" title="Clear chat">
                <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
                  <polyline points="3 6 5 6 21 6"></polyline>
                  <path d="M19 6v14a2 2 0 0 1-2 2H7a2 2 0 0 1-2-2V6m3 0V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"></path>
                </svg>
              </button>
              <button id="chatbot-close-btn" class="chatbot-btn-icon" aria-label="Close chat window" title="Close">
                <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round">
                  <line x1="18" y1="6" x2="6" y2="18"></line>
                  <line x1="6" y1="6" x2="18" y2="18"></line>
                </svg>
              </button>
            </div>
          </div>

          <!-- Messages container -->
          <div id="chatbot-messages" class="chatbot-messages">
            <!-- Messages and suggestion chips render here -->
          </div>

          <!-- Footer & Input -->
          <div class="chatbot-footer">
            <form id="chatbot-form" class="chatbot-form" novalidate>
              <textarea
                id="chatbot-input"
                class="chatbot-input"
                placeholder="Ask Kaira about books, authors, rules..."
                rows="1"
                aria-label="Chat with Kaira"
                autocomplete="off"
              ></textarea>
              <button type="submit" id="chatbot-send-btn" class="chatbot-send-btn" aria-label="Send message" disabled>
                <svg class="chatbot-send-icon" viewBox="0 0 24 24">
                  <path d="M2.01 21L23 12 2.01 3 2 10l15 2-15 2z"/>
                </svg>
              </button>
            </form>
            <div class="chatbot-form-hint">Enter to send, Shift + Enter for new line</div>
          </div>
        </div>
      `;

      document.body.appendChild(root);

      // Cache DOM elements
      dom.root = root;
      dom.fabWrap = root.querySelector('.chatbot-fab-wrap');
      dom.tooltip = document.getElementById('chatbot-fab-tooltip');
      dom.fab = document.getElementById('chatbot-fab');
      dom.window = document.getElementById('chatbot-window');
      dom.messages = document.getElementById('chatbot-messages');
      dom.form = document.getElementById('chatbot-form');
      dom.input = document.getElementById('chatbot-input');
      dom.sendBtn = document.getElementById('chatbot-send-btn');
      dom.clearBtn = document.getElementById('chatbot-clear-btn');
      dom.closeBtn = document.getElementById('chatbot-close-btn');
      dom.badge = document.getElementById('chatbot-badge');

      resolve();
    });
  }

  /**
   * Scroll messages container to the bottom
   */
  function scrollToBottom() {
    if (dom.messages) {
      dom.messages.scrollTop = dom.messages.scrollHeight;
    }
  }

  /**
   * Render User Message Bubble
   */
  function appendUserMessage(text) {
    const row = document.createElement('div');
    row.className = 'chat-row user-row';
    row.innerHTML = `
      <div class="chat-bubble">
        <p>${text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')}</p>
        <span class="chat-time">${getCurrentTime()}</span>
      </div>
    `;
    dom.messages.appendChild(row);
    scrollToBottom();
  }

  /**
   * Render Bot Message Bubble with optional book cards and suggestion chips
   */
  function appendBotMessage(text, books = [], suggestions = []) {
    const row = document.createElement('div');
    row.className = 'chat-row bot-row';

    const formattedHtml = formatMessageText(text);

    let booksHtml = '';
    if (books && books.length > 0) {
      booksHtml = `
        <div class="chatbot-books-grid">
          ${books.map(b => `
            <div class="chatbot-book-card">
              <img
                src="${b.cover || 'assets/images/books/book1.jpg'}"
                alt="${b.title}"
                class="chatbot-book-cover"
                loading="lazy"
                onerror="this.src='assets/images/books/book1.jpg'"
              >
              <div class="chatbot-book-info">
                <a href="book-details.html?id=${b.id}" class="chatbot-book-title" title="${b.title}">${b.title}</a>
                <span class="chatbot-book-author">by ${b.author}</span>
                <div class="chatbot-book-meta">
                  <span class="chatbot-book-rating">⭐ ${b.rating}</span>
                  <span class="chatbot-badge-avail ${b.availability ? 'available' : 'unavailable'}">
                    ${b.availability ? 'Available' : 'Checked Out'}
                  </span>
                </div>
              </div>
              <a href="book-details.html?id=${b.id}" class="chatbot-book-action-btn">View</a>
            </div>
          `).join('')}
        </div>
      `;
    }

    let suggestionsHtml = '';
    if (suggestions && suggestions.length > 0) {
      suggestionsHtml = `
        <div class="chatbot-suggestions-wrap">
          ${suggestions.map(s => `<button type="button" class="chatbot-suggestion-chip" data-prompt="${s}">${s}</button>`).join('')}
        </div>
      `;
    }

    row.innerHTML = `
      <img src="assets/images/kaira-avatar.jpg" alt="Kaira" class="chat-msg-avatar">
      <div class="chat-bubble">
        ${formattedHtml}
        ${booksHtml}
        ${suggestionsHtml}
        <span class="chat-time">${getCurrentTime()}</span>
      </div>
    `;

    dom.messages.appendChild(row);
    scrollToBottom();
  }

  /**
   * Render Typing Indicator
   */
  let typingBubble = null;
  function showTypingIndicator() {
    if (typingBubble) return;
    const row = document.createElement('div');
    row.className = 'chat-row bot-row chatbot-typing-row';
    row.innerHTML = `
      <img src="assets/images/kaira-avatar.jpg" alt="Kaira" class="chat-msg-avatar">
      <div class="chatbot-typing-bubble">
        <span class="chatbot-dot"></span>
        <span class="chatbot-dot"></span>
        <span class="chatbot-dot"></span>
      </div>
    `;
    dom.messages.appendChild(row);
    typingBubble = row;
    scrollToBottom();
  }

  function hideTypingIndicator() {
    if (typingBubble && typingBubble.parentNode) {
      typingBubble.parentNode.removeChild(typingBubble);
    }
    typingBubble = null;
  }

  /**
   * Render Error Message with Retry Button
   */
  function appendErrorMessage(errorMsg, failedMessage) {
    lastFailedMessage = failedMessage;
    const row = document.createElement('div');
    row.className = 'chat-row bot-row';
    row.innerHTML = `
      <div class="chat-bubble" style="border-left: 3px solid #ef4444;">
        <p style="color: #ef4444; font-weight: 600;">⚠️ Connection Alert</p>
        <p>${errorMsg}</p>
        <button type="button" id="chatbot-retry-action" class="chatbot-retry-btn">
          🔄 Retry Sending
        </button>
        <span class="chat-time">${getCurrentTime()}</span>
      </div>
    `;
    dom.messages.appendChild(row);
    scrollToBottom();

    const retryBtn = row.querySelector('#chatbot-retry-action');
    if (retryBtn) {
      retryBtn.addEventListener('click', () => {
        if (lastFailedMessage) {
          row.remove();
          handleSendUserMessage(lastFailedMessage);
        }
      });
    }
  }

  /**
   * Display Default Welcome Greeting
   */
  function renderWelcomeGreeting() {
    // Check if user is logged in
    let userName = '';
    const userJson = sessionStorage.getItem('bn_user') || localStorage.getItem('bn_user');
    if (userJson) {
      try {
        const u = JSON.parse(userJson);
        userName = u.name ? ` ${u.name.split(' ')[0]}` : '';
      } catch (e) {}
    }

    const welcomeText = `Hello${userName}! 👋 I'm **Kaira**, your BookNest AI Assistant. How can I help you today?\n\nAsk me about available books, recommendations, your borrowed titles, or library policies!`;
    const defaultSuggestions = [
      '📚 Available Books',
      '🔍 Find a Book',
      '⭐ Recommend Books',
      '📖 Borrowing Help',
      '🕒 Return Policy',
      '👋 Say Hello'
    ];

    appendBotMessage(welcomeText, [], defaultSuggestions);
  }

  /**
   * Core Message Sending Routine using Native JavaScript Promises
   * Enforces: Promise, async/await, .then(), .catch(), .finally()
   */
  function handleSendUserMessage(messageText) {
    return new Promise((resolve, reject) => {
      const text = (messageText || '').trim();
      if (!text || isSending) {
        return resolve(null);
      }

      // 1. Lock sending state and clear inputs
      isSending = true;
      dom.sendBtn.disabled = true;
      dom.input.value = '';
      dom.input.style.height = 'auto';

      // 2. Render user bubble
      appendUserMessage(text);

      // 3. Display typing indicator
      showTypingIndicator();

      // 4. Send API request using Promise chain
      window.BookNestChatbotAPI.sendMessage(text, conversationId)
        .then((response) => {
          if (response && response.success) {
            // Update conversationId
            if (response.conversationId) {
              conversationId = response.conversationId;
              sessionStorage.setItem('bn_chatbot_conv_id', conversationId);
            }

            // Append bot response
            appendBotMessage(
              response.reply || 'Here is what I found for you!',
              response.books || [],
              response.suggestions || []
            );
            lastFailedMessage = null;
            resolve(response);
          } else {
            throw new Error((response && response.message) || 'Failed to receive a response from Kaira.');
          }
        })
        .catch((err) => {
          console.error('Error handling chatbot response:', err);
          appendErrorMessage(err.message || 'Something went wrong while chatting with Kaira.', text);
          reject(err);
        })
        .finally(() => {
          // 5. Cleanup state in finally block
          hideTypingIndicator();
          isSending = false;
          if (dom.input.value.trim().length > 0) {
            dom.sendBtn.disabled = false;
          }
          dom.input.focus();
        });
    });
  }

  /**
   * Toggle Chatbot Window Open / Close
   */
  function toggleChatbot(forceState) {
    return new Promise((resolve) => {
      isOpen = (typeof forceState === 'boolean') ? forceState : !isOpen;

      if (isOpen) {
        dom.window.classList.add('is-active');
        dom.fab.classList.add('is-open');
        if (dom.fabWrap) dom.fabWrap.classList.add('is-chat-open');
        if (dom.tooltip) {
          dom.tooltip.classList.add('is-hidden');
          dom.tooltip.style.display = 'none';
        }
        if (dom.badge) dom.badge.style.display = 'none'; // Clear notification badge

        // If no messages rendered yet, display welcome message
        if (dom.messages.children.length === 0) {
          renderWelcomeGreeting();
        }

        setTimeout(() => {
          dom.input.focus();
          scrollToBottom();
          resolve(true);
        }, 150);
      } else {
        dom.window.classList.remove('is-active');
        dom.fab.classList.remove('is-open');
        if (dom.fabWrap) dom.fabWrap.classList.remove('is-chat-open');
        if (dom.tooltip) {
          dom.tooltip.classList.remove('is-hidden');
          dom.tooltip.style.display = '';
        }
        resolve(false);
      }
    });
  }

  /**
   * Clear Chat Conversation
   */
  function handleClearChat() {
    return new Promise((resolve) => {
      window.BookNestChatbotAPI.clearConversation(conversationId)
        .then(() => {
          dom.messages.innerHTML = '';
          conversationId = `conv_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;
          sessionStorage.setItem('bn_chatbot_conv_id', conversationId);
          renderWelcomeGreeting();
          resolve();
        })
        .catch(() => {
          dom.messages.innerHTML = '';
          renderWelcomeGreeting();
          resolve();
        });
    });
  }

  /**
   * Setup Event Listeners
   */
  function setupEventListeners() {
    // FAB Toggle
    dom.fab.addEventListener('click', (e) => {
      e.preventDefault();
      toggleChatbot();
    });

    // Close Button
    dom.closeBtn.addEventListener('click', (e) => {
      e.preventDefault();
      toggleChatbot(false);
    });

    // Clear Chat Button
    dom.clearBtn.addEventListener('click', (e) => {
      e.preventDefault();
      if (confirm('Clear your conversation with Kaira?')) {
        handleClearChat();
      }
    });

    // Input changes (enable/disable send button & auto-grow textarea)
    dom.input.addEventListener('input', () => {
      dom.sendBtn.disabled = !dom.input.value.trim() || isSending;
      // Auto-grow
      dom.input.style.height = 'auto';
      dom.input.style.height = Math.min(dom.input.scrollHeight, 84) + 'px';
    });

    // Keydown (Enter to send, Shift+Enter for newline)
    dom.input.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' && !e.shiftKey) {
        e.preventDefault();
        const text = dom.input.value.trim();
        if (text && !isSending) {
          handleSendUserMessage(text);
        }
      }
    });

    // Form Submit
    dom.form.addEventListener('submit', (e) => {
      e.preventDefault();
      const text = dom.input.value.trim();
      if (text && !isSending) {
        handleSendUserMessage(text);
      }
    });

    // Delegate Suggestion Chip clicks inside messages container
    dom.messages.addEventListener('click', (e) => {
      const chip = e.target.closest('.chatbot-suggestion-chip');
      if (chip) {
        e.preventDefault();
        const prompt = chip.getAttribute('data-prompt');
        if (prompt && !isSending) {
          handleSendUserMessage(prompt);
        }
      }
    });

    // Close on Escape key
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && isOpen) {
        toggleChatbot(false);
      }
    });
  }

  /**
   * Main Initialization Routine using Promise.all
   */
  function init() {
    return Promise.resolve()
      .then(() => injectChatbotDOM())
      .then(() => setupEventListeners())
      .then(() => {
        // Expose helper API globally for testing
        window.BookNestChatbot = {
          open: () => toggleChatbot(true),
          close: () => toggleChatbot(false),
          send: (msg) => handleSendUserMessage(msg),
          clear: () => handleClearChat(),
          isOpen: () => isOpen
        };
      })
      .catch((err) => {
        console.error('Failed to initialize BookNest AI Assistant:', err);
      });
  }

  // Initialize once DOM is ready
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
