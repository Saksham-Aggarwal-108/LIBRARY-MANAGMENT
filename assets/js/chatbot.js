  /**
   * Helper: Native Promise to delay/timeout if needed
   */
  function delay(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
  }

  /**
   * Format basic markdown-like syntax into safe HTML
   */
  function formatMessageText(text) {
    if (!text) return '';

    // 1. Extract and preserve code blocks
    const codeBlocks = [];
    let processed = text.replace(/```([a-zA-Z0-9_\-\.\+]*)\n?([\s\S]*?)```/g, (match, lang, code) => {
      const idx = codeBlocks.length;
      const cleanLang = (lang || 'code').toLowerCase().trim();
      const escapedCode = code
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');

      codeBlocks.push(`
        <div class="chatbot-code-block">
          <div class="chatbot-code-header">
            <span class="chatbot-code-lang">${cleanLang}</span>
            <button class="chatbot-copy-code-btn" type="button" data-raw-code="${encodeURIComponent(code)}">📋 Copy Code</button>
          </div>
          <pre><code>${escapedCode}</code></pre>
        </div>
      `);
      return `__CHATBOT_CODE_BLOCK_${idx}__`;
    });

    // 2. Escape general HTML to prevent XSS
    let escaped = processed
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');

    // 3. Allow safe anchor tags for login links generated by our backend
    escaped = escaped.replace(/&lt;a href="([^"]+)" class="([^"]+)"&gt;([^&]+)&lt;\/a&gt;/g, '<a href="$1" class="$2">$3</a>');

    // 4. Inline code: `code`
    escaped = escaped.replace(/`([^`\n]+)`/g, '<code class="chatbot-inline-code">$1</code>');

    // 5. Headings: ### Heading
    escaped = escaped.replace(/^### (.*$)/gim, '<h4 style="margin: 8px 0 4px; color: var(--accent-color);">$1</h4>');

    // 6. Bold: **text**
    escaped = escaped.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');

    // 7. Italic: *text*
    escaped = escaped.replace(/\*(.*?)\*/g, '<em>$1</em>');

    // 8. Lists & Paragraphs
    const lines = escaped.split('\n');
    let inList = false;
    let listType = 'ul';
    let formattedLines = [];

    lines.forEach(line => {
      const trimmed = line.trim();
      const isBullet = trimmed.startsWith('• ') || trimmed.startsWith('- ') || trimmed.startsWith('* ');
      const isNumbered = /^\d+\.\s+/.test(trimmed);

      if (isBullet) {
        if (!inList || listType !== 'ul') {
          if (inList) formattedLines.push(`</${listType}>`);
          inList = true;
          listType = 'ul';
          formattedLines.push('<ul>');
        }
        formattedLines.push(`<li>${trimmed.replace(/^[•\-\*]\s+/, '')}</li>`);
      } else if (isNumbered) {
        if (!inList || listType !== 'ol') {
          if (inList) formattedLines.push(`</${listType}>`);
          inList = true;
          listType = 'ol';
          formattedLines.push('<ol>');
        }
        formattedLines.push(`<li>${trimmed.replace(/^\d+\.\s+/, '')}</li>`);
      } else {
        if (inList) {
          inList = false;
          formattedLines.push(`</${listType}>`);
        }
        if (trimmed.length > 0) {
          formattedLines.push(`<p>${line}</p>`);
        }
      }
    });

    if (inList) {
      formattedLines.push(`</${listType}>`);
    }

    let resultHtml = formattedLines.join('');

    // 9. Reinsert code blocks
    codeBlocks.forEach((blockHtml, idx) => {
      resultHtml = resultHtml.replace(`<p>__CHATBOT_CODE_BLOCK_${idx}__</p>`, blockHtml);
      resultHtml = resultHtml.replace(`__CHATBOT_CODE_BLOCK_${idx}__`, blockHtml);
    });

    return resultHtml;
  }

  /**
   * Format current time (e.g. "10:30 AM")
   */
  function getCurrentTime() {
    const now = new Date();
    return now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  }

